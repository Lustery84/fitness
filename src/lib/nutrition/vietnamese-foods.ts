function stripDiacritics(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase()
    .trim();
}

export function searchFoods(query: string): FoodItem[] {
  const q = stripDiacritics(query);
  if (!q) return VIETNAMESE_FOODS;
  const terms = q.split(/\s+/).filter(Boolean);
  return VIETNAMESE_FOODS.filter((item) => {
    const haystack = stripDiacritics(`${item.name} ${item.nameEn} ${item.category}`);
    return terms.every((t) => haystack.includes(t));
  });
}

export function scaleFoodMacros(food: FoodItem, multiplier: number) {
  const safeMult = Math.max(0.1, multiplier);
  return {
    grams: Math.round(food.servingGrams * safeMult),
    calories: Math.round(food.calories * safeMult),
    proteinG: Math.round(food.proteinG * safeMult * 10) / 10,
    carbsG: Math.round(food.carbsG * safeMult * 10) / 10,
    fatG: Math.round(food.fatG * safeMult * 10) / 10,
  };
}
